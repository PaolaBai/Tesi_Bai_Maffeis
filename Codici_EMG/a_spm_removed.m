%% ============================================================
% SnPM 1D NON PARAMETRICO - UNIVERSALE
%
% FUNZIONA AUTOMATICAMENTE PER:
%
%   PHASE A
%   XSENS vs OPTO
%   Sistema da validare = Xsens
%   Riferimento         = Opto
%   Differenza          = Xsens - Opto
%
%   PHASE B
%   CAPTURY vs XSENS
%   Sistema da validare = Captury
%   Riferimento         = Xsens
%   Differenza          = Captury - Xsens
%
% INPUT:
% Foglio Excel: SPM_ALL
%
% Colonne comuni:
% Task
% Soggetto
% Lato
% Istante
%
% + una delle due combinazioni:
%
% Opto_mean_deg + Xsens_mean_deg
%
% oppure
%
% Xsens_mean_deg + Captury_mean_deg
%
%
% OUTPUT AUTOMATICI:
%
% 1) Figura SnPM .fig
% 2) Figura SnPM .png 300 dpi
% 3) Excel risultati:
%       - Summary
%       - SPM_Curve
%       - Significant_Clusters
% 4) Workspace .mat
%
% Il grafico Mediana + IQR viene mostrato ma NON salvato.
%% ============================================================


clear;
clc;
close all;


%% ============================================================
% 1. PERCORSO SPM1D
%% ============================================================

spm1dPath = ...
    'C:\Users\LocalUser\Documents\MATLAB\spm1dmatlab-master';

addpath(spm1dPath);


% Aggiunge spm8 se presente

spm8Path = fullfile(spm1dPath,'spm8');

if isfolder(spm8Path)
    addpath(spm8Path);
end


%% CONTROLLO INSTALLAZIONE SPM1D

spmFunction = which( ...
    'spm1d.stats.nonparam.ttest_paired');


if isempty(spmFunction)

    error([ ...
        'SPM1D non trovato.' newline ...
        'Controlla il percorso:' newline ...
        spm1dPath]);

else

    fprintf('\n============================================\n');
    fprintf('SPM1D TROVATO CORRETTAMENTE\n');
    fprintf('============================================\n');
    fprintf('%s\n\n',spmFunction);

end


%% ============================================================
% 2. SELEZIONE FILE EXCEL
%% ============================================================

[fileName,filePath] = uigetfile( ...
    '*.xlsx', ...
    'Seleziona il file per SnPM');


if isequal(fileName,0)

    error('Nessun file selezionato.');

end


inputFile = fullfile( ...
    filePath, ...
    fileName);


fprintf('File selezionato:\n');
fprintf('%s\n\n',inputFile);


%% ============================================================
% 3. LETTURA DATI
%% ============================================================

T = readtable( ...
    inputFile, ...
    'Sheet','SPM_ALL', ...
    'VariableNamingRule','preserve');


%% ============================================================
% 4. CONTROLLO COLONNE BASE
%% ============================================================

baseColumns = { ...
    'Task', ...
    'Soggetto', ...
    'Lato', ...
    'Istante'};


for i = 1:numel(baseColumns)

    if ~ismember( ...
            baseColumns{i}, ...
            T.Properties.VariableNames)

        error( ...
            'Colonna mancante: %s', ...
            baseColumns{i});

    end

end


%% ============================================================
% 5. RIMOZIONE RIGHE COMPLETAMENTE VUOTE
%% ============================================================

emptyRows = all(ismissing(T),2);

T(emptyRows,:) = [];


%% ============================================================
% 6. RICONOSCIMENTO AUTOMATICO DEL CONFRONTO
%% ============================================================

variableNames = T.Properties.VariableNames;


hasOpto = ...
    ismember('Opto_mean_deg',variableNames);

hasXsens = ...
    ismember('Xsens_mean_deg',variableNames);

hasCaptury = ...
    ismember('Captury_mean_deg',variableNames);


%% ------------------------------------------------------------
% CASO 1:
% XSENS vs OPTO
%
% Xsens  = da validare
% Opto   = riferimento
%% ------------------------------------------------------------

if hasOpto && hasXsens && ~hasCaptury

    validName = "Xsens";
    refName   = "Opto";

    validColumn = 'Xsens_mean_deg';
    refColumn   = 'Opto_mean_deg';

    phaseName = "Phase A";



%% ------------------------------------------------------------
% CASO 2:
% CAPTURY vs XSENS
%
% Captury = da validare
% Xsens   = riferimento
%% ------------------------------------------------------------

elseif hasXsens && hasCaptury && ~hasOpto

    validName = "Captury";
    refName   = "Xsens";

    validColumn = 'Captury_mean_deg';
    refColumn   = 'Xsens_mean_deg';

    phaseName = "Phase B";


else

    error([ ...
        'Impossibile riconoscere automaticamente il confronto.' newline ...
        newline ...
        'Il file deve contenere:' newline ...
        'Opto_mean_deg + Xsens_mean_deg' newline ...
        'oppure' newline ...
        'Xsens_mean_deg + Captury_mean_deg']);

end


fprintf('============================================\n');
fprintf('CONFRONTO RICONOSCIUTO AUTOMATICAMENTE\n');
fprintf('============================================\n');

fprintf('Fase: %s\n',phaseName);
fprintf('Sistema da validare: %s\n',validName);
fprintf('Sistema di riferimento: %s\n',refName);

fprintf('Differenza analizzata: %s - %s\n\n', ...
    validName,refName);


%% ============================================================
% 7. RICONOSCIMENTO AUTOMATICO TASK E LATO
%% ============================================================

taskValues = unique( ...
    string(T.Task));

taskValues = taskValues( ...
    taskValues ~= "" & ...
    ~ismissing(taskValues));


sideValues = unique( ...
    string(T.Lato));

sideValues = sideValues( ...
    sideValues ~= "" & ...
    ~ismissing(sideValues));


if numel(taskValues) ~= 1

    error( ...
        'Il file deve contenere un solo Task.');

end


if numel(sideValues) ~= 1

    error( ...
        'Il file deve contenere un solo Lato.');

end


taskName = taskValues(1);
sideName = sideValues(1);


analysisName = ...
    taskName + "_" + sideName;


plotName = ...
    taskName + " " + sideName;


comparisonName = ...
    validName + "_vs_" + refName;


fprintf('Task: %s\n',taskName);
fprintf('Lato: %s\n',sideName);

fprintf('Nome analisi: %s\n\n', ...
    analysisName);


%% ============================================================
% 8. IDENTIFICAZIONE SOGGETTI
%% ============================================================

subjects = unique( ...
    string(T.Soggetto), ...
    'stable');


subjects = subjects( ...
    subjects ~= "" & ...
    ~ismissing(subjects));


nSubjects = numel(subjects);


fprintf('Numero soggetti: %d\n', ...
    nSubjects);

fprintf('Soggetti:\n');

disp(subjects);


%% ============================================================
% 9. IDENTIFICAZIONE ISTANTI
%% ============================================================

timePoints = sort( ...
    unique(T.Istante));


nTime = numel(timePoints);


fprintf('Numero istanti: %d\n\n', ...
    nTime);


if nTime ~= 101

    warning( ...
        'Trovati %d istanti invece di 101.', ...
        nTime);

end


%% ============================================================
% 10. CREAZIONE MATRICI
%
% Righe   = soggetti
% Colonne = istanti
%
% Y_VALID = sistema da validare
% Y_REF   = sistema di riferimento
%% ============================================================

Y_VALID = nan( ...
    nSubjects, ...
    nTime);


Y_REF = nan( ...
    nSubjects, ...
    nTime);


for s = 1:nSubjects

    subj = subjects(s);


    %% selezione soggetto

    idx = ...
        string(T.Soggetto) == subj;


    Ts = T(idx,:);


    %% ordinamento

    Ts = sortrows( ...
        Ts, ...
        'Istante');


    %% controllo numero punti

    if height(Ts) ~= nTime

        error([ ...
            'Il soggetto %s presenta %d punti ' ...
            'invece dei %d attesi.'], ...
            subj, ...
            height(Ts), ...
            nTime);

    end


    %% controllo istanti

    if ~isequal( ...
            Ts.Istante, ...
            timePoints)

        error([ ...
            'Gli istanti del soggetto %s ' ...
            'non coincidono con quelli attesi.'], ...
            subj);

    end


    %% inserimento dati

    Y_VALID(s,:) = ...
        Ts.(validColumn)';


    Y_REF(s,:) = ...
        Ts.(refColumn)';

end


%% ============================================================
% 11. CONTROLLO DATI
%% ============================================================

if any(~isfinite(Y_VALID(:)))

    error( ...
        'Sono presenti NaN o Inf nei dati %s.', ...
        validName);

end


if any(~isfinite(Y_REF(:)))

    error( ...
        'Sono presenti NaN o Inf nei dati %s.', ...
        refName);

end


fprintf('Matrice %s: %d x %d\n', ...
    validName, ...
    size(Y_VALID,1), ...
    size(Y_VALID,2));


fprintf('Matrice %s: %d x %d\n\n', ...
    refName, ...
    size(Y_REF,1), ...
    size(Y_REF,2));


%% ============================================================
% 12. SnPM PAIRED NON PARAMETRICO
%% ============================================================

alpha = 0.05;

twoTailed = true;

iterations = -1;

clusterMetric = ...
    'MaxClusterIntegral';


% ============================================================
% IMPORTANTE:
%
% Primo input  = SISTEMA DA VALIDARE
% Secondo input = RIFERIMENTO
%
% Quindi:
%
% PHASE A
% Xsens - Opto
%
% PHASE B
% Captury - Xsens
%
% SnPM{t} positivo:
% sistema da validare > riferimento
%
% SnPM{t} negativo:
% sistema da validare < riferimento
%% ============================================================


snpm = ...
    spm1d.stats.nonparam.ttest_paired( ...
        Y_VALID, ...
        Y_REF);


snpmi = snpm.inference( ...
    alpha, ...
    'two_tailed',twoTailed, ...
    'iterations',iterations, ...
    'interp',true, ...
    'circular',false, ...
    'cluster_metric',clusterMetric);


%% ============================================================
% 13. RISULTATI PRINCIPALI
%% ============================================================

z = snpmi.z(:);

zstar = snpmi.zstar;

h0reject = snpmi.h0reject;

nClusters = snpmi.nClusters;

pClusters = snpmi.p(:);


% Numero permutazioni effettivamente utilizzate

nPermActual = snpmi.nPermActual;

nPermUnique = snpmi.nPermUnique;


fprintf('\n');
fprintf('============================================\n');
fprintf('RISULTATI SnPM NON PARAMETRICO\n');
fprintf('============================================\n');

fprintf('Analisi: %s\n',analysisName);

fprintf('Fase: %s\n',phaseName);

fprintf('Sistema da validare: %s\n', ...
    validName);

fprintf('Riferimento: %s\n', ...
    refName);

fprintf('Differenza: %s - %s\n', ...
    validName,refName);

fprintf('Soggetti: %d\n', ...
    nSubjects);

fprintf('Istanti: %d\n', ...
    nTime);

fprintf('Alpha: %.3f\n', ...
    alpha);

fprintf('Two-tailed: TRUE\n');

fprintf('Cluster metric: %s\n', ...
    clusterMetric);

fprintf('Permutazioni effettive: %d\n', ...
    nPermActual);

fprintf('Permutazioni uniche: %d\n', ...
    nPermUnique);

fprintf('Critical threshold: %.6f\n', ...
    zstar);

fprintf('Cluster significativi: %d\n', ...
    nClusters);

fprintf('H0 rejected: %d\n', ...
    h0reject);

fprintf('============================================\n\n');


disp(snpmi);


%% ============================================================
% 14. DESCRITTIVE DELLE CURVE
%% ============================================================

% Sistema da validare

medianVALID = ...
    median(Y_VALID,1)';

q1VALID = ...
    prctile(Y_VALID,25,1)';

q3VALID = ...
    prctile(Y_VALID,75,1)';


% Riferimento

medianREF = ...
    median(Y_REF,1)';

q1REF = ...
    prctile(Y_REF,25,1)';

q3REF = ...
    prctile(Y_REF,75,1)';


%% DIFFERENZA PAIRED

Y_DIFF = ...
    Y_VALID - Y_REF;


medianDIFF = ...
    median(Y_DIFF,1)';

q1DIFF = ...
    prctile(Y_DIFF,25,1)';

q3DIFF = ...
    prctile(Y_DIFF,75,1)';


%% ============================================================
% 15. TABELLA CURVA SnPM
%% ============================================================

Time = timePoints(:);


PositiveThreshold = ...
    repmat( ...
        zstar, ...
        nTime, ...
        1);


NegativeThreshold = ...
    repmat( ...
        -zstar, ...
        nTime, ...
        1);


SignificantNode = ...
    abs(z) >= zstar;


SPM_Curve = table( ...
    Time, ...
    z, ...
    PositiveThreshold, ...
    NegativeThreshold, ...
    SignificantNode, ...
    medianVALID, ...
    q1VALID, ...
    q3VALID, ...
    medianREF, ...
    q1REF, ...
    q3REF, ...
    medianDIFF, ...
    q1DIFF, ...
    q3DIFF, ...
    'VariableNames',{ ...
        'MovementCycle_percent', ...
        'SnPM_t', ...
        'PositiveThreshold', ...
        'NegativeThreshold', ...
        'SignificantNode', ...
        'Median_SystemToValidate_deg', ...
        'Q1_SystemToValidate_deg', ...
        'Q3_SystemToValidate_deg', ...
        'Median_Reference_deg', ...
        'Q1_Reference_deg', ...
        'Q3_Reference_deg', ...
        'Median_PairedDifference_deg', ...
        'Q1_PairedDifference_deg', ...
        'Q3_PairedDifference_deg'});


%% ============================================================
% 16. ESTRAZIONE CLUSTER SIGNIFICATIVI
%
% I cluster vengono presi DIRETTAMENTE dall'oggetto SPM1D
% snpmi.clusters
%% ============================================================

if nClusters > 0

    Cluster = ...
        (1:nClusters)';


    Start_percent = ...
        nan(nClusters,1);


    End_percent = ...
        nan(nClusters,1);


    Direction = ...
        strings(nClusters,1);


    Peak_percent = ...
        nan(nClusters,1);


    Peak_SnPM_t = ...
        nan(nClusters,1);


    Cluster_p_value = ...
        nan(nClusters,1);


    Cluster_extent_nodes = ...
        nan(nClusters,1);


    Cluster_centroid_percent = ...
        nan(nClusters,1);


    Cluster_metric_value = ...
        nan(nClusters,1);


    Cluster_metric_label = ...
        strings(nClusters,1);


    Cluster_sign = ...
        nan(nClusters,1);


    %% coordinate SPM
    %
    % SPM usa:
    % 0 ... nTime-1
    %
    % Le convertiamo nei valori reali di timePoints

    nodeAxis = ...
        (0:nTime-1)';


    for c = 1:nClusters

        cl = snpmi.clusters{c};


        %% ---------------------------------------------
        % ENDPOINTS DEL CLUSTER
        %% ---------------------------------------------

        endpoints = cl.endpoints;


        % circular=false, quindi non dovrebbero
        % essere celle

        if iscell(endpoints)

            error([ ...
                'Cluster circolare inatteso. ' ...
                'Il codice è impostato con circular=false.']);

        end


        startNode = endpoints(1);

        endNode = endpoints(2);


        Start_percent(c) = interp1( ...
            nodeAxis, ...
            timePoints(:), ...
            startNode, ...
            'linear', ...
            'extrap');


        End_percent(c) = interp1( ...
            nodeAxis, ...
            timePoints(:), ...
            endNode, ...
            'linear', ...
            'extrap');


        %% ---------------------------------------------
        % SEGNO / DIREZIONE
        %% ---------------------------------------------

        Cluster_sign(c) = ...
            cl.csign;


        if cl.csign > 0

            Direction(c) = ...
                validName + " > " + refName;

        else

            Direction(c) = ...
                validName + " < " + refName;

        end


        %% ---------------------------------------------
        % P-VALUE CLUSTER
        %% ---------------------------------------------

        Cluster_p_value(c) = ...
            cl.P;


        %% ---------------------------------------------
        % ESTENSIONE
        %% ---------------------------------------------

        Cluster_extent_nodes(c) = ...
            cl.extent;


        %% ---------------------------------------------
        % CENTROIDE
        %% ---------------------------------------------

        centroidNode = ...
            cl.xy(1);


        Cluster_centroid_percent(c) = ...
            interp1( ...
                nodeAxis, ...
                timePoints(:), ...
                centroidNode, ...
                'linear', ...
                'extrap');


        %% ---------------------------------------------
        % METRICA NON PARAMETRICA
        %% ---------------------------------------------

        Cluster_metric_value(c) = ...
            cl.metric_value;


        Cluster_metric_label(c) = ...
            string(cl.metric_label);


        %% ---------------------------------------------
        % PICCO SnPM{t}
        %% ---------------------------------------------

        firstNode = max( ...
            0, ...
            ceil(startNode));


        lastNode = min( ...
            nTime-1, ...
            floor(endNode));


        nodeIndices = ...
            firstNode:lastNode;


        matlabIndices = ...
            nodeIndices + 1;


        if isempty(matlabIndices)

            % sicurezza aggiuntiva

            [~,nearestIndex] = ...
                min(abs( ...
                    nodeAxis - centroidNode));

            matlabIndices = ...
                nearestIndex;

        end


        if cl.csign > 0

            [peakValue,localPeak] = ...
                max(z(matlabIndices));

        else

            [peakValue,localPeak] = ...
                min(z(matlabIndices));

        end


        peakMatlabIndex = ...
            matlabIndices(localPeak);


        Peak_SnPM_t(c) = ...
            peakValue;


        Peak_percent(c) = ...
            timePoints(peakMatlabIndex);

    end


    %% TABELLA CLUSTER

    Significant_Clusters = table( ...
        Cluster, ...
        Start_percent, ...
        End_percent, ...
        Direction, ...
        Peak_percent, ...
        Peak_SnPM_t, ...
        Cluster_p_value, ...
        Cluster_extent_nodes, ...
        Cluster_centroid_percent, ...
        Cluster_metric_label, ...
        Cluster_metric_value, ...
        Cluster_sign, ...
        'VariableNames',{ ...
            'Cluster', ...
            'Start_percent', ...
            'End_percent', ...
            'Direction', ...
            'Peak_percent', ...
            'Peak_SnPM_t', ...
            'Cluster_p_value', ...
            'Cluster_extent_nodes', ...
            'Cluster_centroid_percent', ...
            'Cluster_metric_label', ...
            'Cluster_metric_value', ...
            'Cluster_sign'});


else

    %% TABELLA VUOTA SE NON CI SONO CLUSTER

    Significant_Clusters = table( ...
        zeros(0,1), ...
        zeros(0,1), ...
        zeros(0,1), ...
        strings(0,1), ...
        zeros(0,1), ...
        zeros(0,1), ...
        zeros(0,1), ...
        zeros(0,1), ...
        zeros(0,1), ...
        strings(0,1), ...
        zeros(0,1), ...
        zeros(0,1), ...
        'VariableNames',{ ...
            'Cluster', ...
            'Start_percent', ...
            'End_percent', ...
            'Direction', ...
            'Peak_percent', ...
            'Peak_SnPM_t', ...
            'Cluster_p_value', ...
            'Cluster_extent_nodes', ...
            'Cluster_centroid_percent', ...
            'Cluster_metric_label', ...
            'Cluster_metric_value', ...
            'Cluster_sign'});

end


%% ============================================================
% 17. TABELLA SUMMARY
%% ============================================================

if h0reject

    h0Text = "TRUE";

else

    h0Text = "FALSE";

end


SummaryParameter = [ ...
    "Analysis"; ...
    "Phase"; ...
    "System_to_validate"; ...
    "Reference_system"; ...
    "Difference"; ...
    "Statistical_test"; ...
    "N_subjects"; ...
    "N_nodes"; ...
    "Alpha"; ...
    "Two_tailed"; ...
    "Iterations_requested"; ...
    "N_permutations_actual"; ...
    "N_permutations_unique"; ...
    "Cluster_metric"; ...
    "Critical_threshold"; ...
    "H0_rejected"; ...
    "N_significant_clusters"];


SummaryValue = [ ...
    string(analysisName); ...
    string(phaseName); ...
    string(validName); ...
    string(refName); ...
    validName + " - " + refName; ...
    "Paired non-parametric SnPM"; ...
    string(nSubjects); ...
    string(nTime); ...
    string(alpha); ...
    "TRUE"; ...
    string(iterations); ...
    string(nPermActual); ...
    string(nPermUnique); ...
    string(clusterMetric); ...
    string(zstar); ...
    h0Text; ...
    string(nClusters)];


Summary = table( ...
    SummaryParameter, ...
    SummaryValue, ...
    'VariableNames',{ ...
        'Parameter', ...
        'Value'});


%% ============================================================
% 18. NOMI AUTOMATICI OUTPUT
%% ============================================================

outputBaseName = ...
    analysisName + ...
    "_SnPM_" + ...
    comparisonName;


figName = ...
    outputBaseName + ".fig";


pngName = ...
    outputBaseName + ".png";


excelName = ...
    outputBaseName + "_RESULTS.xlsx";


matName = ...
    outputBaseName + "_RESULTS.mat";


figOutput = fullfile( ...
    filePath, ...
    char(figName));


pngOutput = fullfile( ...
    filePath, ...
    char(pngName));


excelOutput = fullfile( ...
    filePath, ...
    char(excelName));


matOutput = fullfile( ...
    filePath, ...
    char(matName));


%% ============================================================
% 19. FIGURA SnPM
%% ============================================================

figSPM = figure( ...
    'Color','w', ...
    'Name',char(outputBaseName));


snpmi.plot();

snpmi.plot_threshold_label();

snpmi.plot_p_values();


xlabel( ...
    'Movement cycle (%)');


ylabel( ...
    'SnPM{t}');


title( ...
    sprintf( ...
        '%s - %s vs %s', ...
        char(plotName), ...
        char(validName), ...
        char(refName)), ...
    'Interpreter','none');


grid on;

box off;


%% ============================================================
% 20. SALVATAGGIO FIGURA SnPM
%% ============================================================

savefig( ...
    figSPM, ...
    figOutput);


exportgraphics( ...
    figSPM, ...
    pngOutput, ...
    'Resolution',300);


%% ============================================================
% 21. SALVATAGGIO EXCEL RISULTATI
%% ============================================================

% Se esiste già, viene sostituito

if isfile(excelOutput)

    delete(excelOutput);

end


%% SUMMARY

writetable( ...
    Summary, ...
    excelOutput, ...
    'Sheet','Summary');


%% CURVA SPM COMPLETA

writetable( ...
    SPM_Curve, ...
    excelOutput, ...
    'Sheet','SPM_Curve');


%% CLUSTER SIGNIFICATIVI

writetable( ...
    Significant_Clusters, ...
    excelOutput, ...
    'Sheet','Significant_Clusters');


%% ============================================================
% 22. SALVATAGGIO FILE .MAT
%% ============================================================

% Salva:
% - dati originali usati
% - differenze
% - oggetto SnPM
% - inferenza
% - tabelle risultati
% - metadata


try

    save( ...
        matOutput, ...
        'inputFile', ...
        'analysisName', ...
        'phaseName', ...
        'validName', ...
        'refName', ...
        'validColumn', ...
        'refColumn', ...
        'subjects', ...
        'timePoints', ...
        'Y_VALID', ...
        'Y_REF', ...
        'Y_DIFF', ...
        'snpm', ...
        'snpmi', ...
        'alpha', ...
        'twoTailed', ...
        'iterations', ...
        'clusterMetric', ...
        'z', ...
        'zstar', ...
        'h0reject', ...
        'nClusters', ...
        'pClusters', ...
        'nPermActual', ...
        'nPermUnique', ...
        'Summary', ...
        'SPM_Curve', ...
        'Significant_Clusters');


catch ME

    warning([ ...
        'Non è stato possibile salvare gli oggetti SPM ' ...
        'nel file MAT. Verranno salvati tutti i risultati numerici.']);

    fprintf( ...
        'Messaggio MATLAB: %s\n', ...
        ME.message);


    save( ...
        matOutput, ...
        'inputFile', ...
        'analysisName', ...
        'phaseName', ...
        'validName', ...
        'refName', ...
        'validColumn', ...
        'refColumn', ...
        'subjects', ...
        'timePoints', ...
        'Y_VALID', ...
        'Y_REF', ...
        'Y_DIFF', ...
        'alpha', ...
        'twoTailed', ...
